#include <STC32G.H>
#include "intrins.h"
#include "delay.h"
#define MAIN_Fosc        24000000UL   //定义主时钟

sbit LED_L=P3^4;		//重定义左前车灯LED
sbit LED_R=P0^5;		//重定义右前车灯LED

/********************* 函数声明 *************************/ 
 

/********************* 主函数 *************************/
void main2()
{
   WTST = 0;  //设置程序指令延时参数，赋值为0可将CPU执行指令的速度设置为最快
   EAXFR = 1; //扩展寄存器(XFR)访问使能
   CKCON = 0; //提高访问XRAM速度
	
	 P3M0 = 0x10;        //将P3.4口单独设置为推挽输出模式  0001 0000
   P3M1 = 0x00;
	
	 P0M0 = 0x20;        //将P0.5口单独设置为推挽输出模式  0010 0000
   P0M1 = 0x00;
	
   while (1)
	{
 		LED_L=1;	      //高电平点亮左前车灯
		LED_R=1;	      //高电平点亮右前车灯
		delay_ms(200);  //延时200ms
		delay_ms(200);  //延时200ms
 		LED_L=0;	      //低电平熄灭左前车灯
		LED_R=0;	      //低电平熄灭右前车灯
		delay_ms(200);  //延时200ms
		delay_ms(200);  //延时200ms
	}
} 


